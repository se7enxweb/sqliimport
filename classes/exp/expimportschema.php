    /**
     * The schema handler for an engine (mysql, postgresql, sqlite, oracle).
     * @return eZDBSchemaInterface|null
     */
    public static function handler( $engine, array $schema, $db = null )
    {
        $classes = array( 'mysql' => 'eZMysqlSchema', 'postgresql' => 'eZPgsqlSchema', 'sqlite' => 'eZSQLiteSchema',
                          'oracle' => 'eZOracleSchema' );
        if ( !isset( $classes[$engine] ) )
            return null;
        $class = $classes[$engine];
        if ( !class_exists( $class ) && $engine === 'oracle' && class_exists( 'eZExtension' ) )
        {
            $file = eZExtension::baseDirectory() . '/ezoracle/ezdb/dbms-schema/ezoracleschema.php';
            if ( is_file( $file ) )
                require_once $file;
        }
        if ( !class_exists( $class ) )
            return null;
        return new $class( array( 'schema' => $schema, 'instance' => $db, 'type' => $engine ) );
    }

    /** @return string[] SQL statements of the engine for the given tables (all when empty) */
    public static function sqlStatements( $engine, array $tables = array() )
    {
        $schema = self::definition();
        $handler = self::handler( $engine, $schema );
        if ( !$handler )
            return array();
        $local = $schema;
        $local['_info'] = array( 'format' => 'generic' );
        $handler->transformSchema( $local, true );
        unset( $local['_info'] );
        $out = array();
        foreach ( $local as $table => $def )
        {
            if ( $tables && !in_array( $table, $tables, true ) )
                continue;
            foreach ( $handler->generateTableSQLList( $table, $def, array( 'format' => 'local', 'table_type' => $engine === 'mysql' ? 'innodb' : '' ), false ) as $statement )
            {
                $statement = trim( $statement );
                // PL/SQL blocks (Oracle sequences and triggers) end in "END;", which belongs to them
                if ( !preg_match( '/^(BEGIN\b|CREATE OR REPLACE TRIGGER\b)/i', $statement ) )
                    $statement = rtrim( $statement, ';' );
                if ( $statement !== '' )
                    $out[] = $statement;
            }
        }
        return $out;
    }

    /** @return string engine name of a database connection */
    public static function engineOf( eZDBInterface $db )
    {
        $name = strtolower( (string)$db->databaseName() );
        if ( $name === 'postgresql' || $name === 'pgsql' )
            return 'postgresql';
        if ( strpos( $name, 'sqlite' ) === 0 )
            return 'sqlite';
        if ( strpos( $name, 'mongo' ) === 0 )
            return 'mongodb';
        return $name;
    }

    /** @return string[] the tables missing in the database */
    public static function missingTables( $db = null )
    {
        $db = $db ?: eZDB::instance();
        return array_values( array_diff( self::tables(), self::existingTables( $db ) ) );
    }

    /**
     * The tables of the extension that exist. eZTableList() of the drivers lists only tables named ez*, so each engine
     * is asked directly.
     * @return string[]
     */
    public static function existingTables( $db = null )
    {
        $db = $db ?: eZDB::instance();
        switch ( self::engineOf( $db ) )
        {
            case 'sqlite':
                $sql = "SELECT name FROM sqlite_master WHERE type='table' AND name LIKE 'sqliimport%'";
                break;
            case 'mysql':
                $sql = "SELECT table_name AS name FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name LIKE 'sqliimport%'";
                break;
            case 'postgresql':
                $sql = "SELECT relname AS name FROM pg_class WHERE relkind = 'r' AND relname LIKE 'sqliimport%'";
                break;
            case 'oracle':
                $sql = "SELECT LOWER(table_name) AS name FROM user_tables WHERE table_name LIKE 'SQLIIMPORT%'";
                break;
            default:
                return array_values( array_intersect( self::tables(), array_map( 'strtolower', array_keys( $db->eZTableList() ) ) ) );
        }
        $names = array();
        foreach ( (array)$db->arrayQuery( $sql ) as $row )
        {
            $row = array_change_key_case( $row, CASE_LOWER );
            $names[] = strtolower( (string)( isset( $row['name'] ) ? $row['name'] : reset( $row ) ) );
        }
        return array_values( array_intersect( self::tables(), $names ) );
    }

    /**
     * The columns of a table in the database.
     * @return string[]|null lower-case names, null when the engine cannot tell
     */
    public static function existingColumns( $table, $db = null )
    {
        $db = $db ?: eZDB::instance();
        $table = preg_replace( '/[^a-z_]/', '', (string)$table );
        switch ( self::engineOf( $db ) )
        {
            case 'sqlite':
                $rows = $db->arrayQuery( "PRAGMA table_info($table)" );
                break;
            case 'mysql':
                $rows = $db->arrayQuery( "SELECT column_name AS name FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = '$table'" );
                break;
            case 'postgresql':
                $rows = $db->arrayQuery( "SELECT column_name AS name FROM information_schema.columns WHERE table_name = '$table'" );
                break;
            case 'oracle':
                $rows = $db->arrayQuery( "SELECT LOWER(column_name) AS name FROM user_tab_columns WHERE table_name = '" . strtoupper( $table ) . "'" );
                break;
            default:
                return null;
        }
        $out = array();
        foreach ( (array)$rows as $row )
        {
            $row = array_change_key_case( $row, CASE_LOWER );
            if ( isset( $row['name'] ) )
                $out[] = strtolower( (string)$row['name'] );
        }
        return $out;
    }

    /** @return string[]|null the index names of a table in the database (lower case), null when unknown */
    public static function existingIndexes( $table, $db = null )
    {
        $db = $db ?: eZDB::instance();
        $table = preg_replace( '/[^a-z_]/', '', (string)$table );
        switch ( self::engineOf( $db ) )
        {
            case 'sqlite':
                $sql = "SELECT name FROM sqlite_master WHERE type = 'index' AND tbl_name = '$table'";
                break;
            case 'mysql':
                $sql = "SELECT DISTINCT index_name AS name FROM information_schema.statistics WHERE table_schema = DATABASE() AND table_name = '$table'";
                break;
            case 'postgresql':
                $sql = "SELECT indexname AS name FROM pg_indexes WHERE tablename = '$table'";
                break;
            case 'oracle':
                $sql = "SELECT LOWER(index_name) AS name FROM user_indexes WHERE table_name = '" . strtoupper( $table ) . "'";
                break;
            default:
                return null;
        }
        $out = array();
        foreach ( (array)$db->arrayQuery( $sql ) as $row )
        {
            $row = array_change_key_case( $row, CASE_LOWER );
            $name = strtolower( (string)$row['name'] );
            $out[] = $name;
            // the SQLite handler names an index <table>__<index>
            if ( strpos( $name, $table . '__' ) === 0 )
                $out[] = substr( $name, strlen( $table ) + 2 );
        }
        return $out;
    }

    /**
     * The columns and indexes of the existing tables that the database lacks (an installation of an earlier state).
     * The 1.x tables are left as they are.
     * @return string[] list of "table.column" and "table index name"
     */
    public static function missingColumns( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $out = array();
        $existing = self::existingTables( $db );
        $legacy = array_keys( self::legacyDefinition() );
        foreach ( self::definition() as $table => $def )
        {
            if ( !in_array( $table, $existing, true ) || in_array( $table, $legacy, true ) )
                continue;
            $columns = self::existingColumns( $table, $db );
            if ( $columns !== null )
                foreach ( array_keys( $def['fields'] ) as $field )
                    if ( !in_array( $field, $columns, true ) )
                        $out[] = "$table.$field";
            $indexes = self::existingIndexes( $table, $db );
            if ( $indexes !== null )
                foreach ( $def['indexes'] as $name => $index )
                    if ( $name !== 'PRIMARY' && !in_array( strtolower( $name ), $indexes, true ) )
                        $out[] = "$table index $name";
        }
        return $out;
    }

    /**
     * The statements that add the missing columns and indexes, generated by the engine's schema handler.
     * @return string[]
     */
    public static function upgradeStatements( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $schema = self::definition();
        $handler = self::handler( self::engineOf( $db ), $schema );
        if ( !$handler )
            return array();
        $local = $schema;
        $local['_info'] = array( 'format' => 'generic' );
        $handler->transformSchema( $local, true );
        $statements = array();
        foreach ( self::missingColumns( $db ) as $missing )
        {
            if ( preg_match( '/^(\w+)\.(\w+)$/', $missing, $m ) )
                $sql = $handler->generateAddFieldSql( $m[1], $m[2], $local[$m[1]]['fields'][$m[2]], array( 'format' => 'local' ) );
            elseif ( preg_match( '/^(\w+) index (\w+)$/', $missing, $m ) )
                $sql = $handler->generateAddIndexSql( $m[1], $m[2], $local[$m[1]]['indexes'][$m[2]], array( 'format' => 'local' ) );
            else
                continue;
            foreach ( preg_split( '/;\s*\n/', (string)$sql ) as $statement )
                if ( trim( $statement ) !== '' )
                    $statements[] = rtrim( trim( $statement ), ';' );
        }
        return $statements;
    }

    /**
     * Creates the missing tables, columns and indexes in the database (idempotent). Existing tables and rows are never
     * dropped or rewritten.
     * @return array ( string[] created, string[] errors )
     */
    public static function ensure( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $engine = self::engineOf( $db );
        $created = array();
        $errors = array();
        foreach ( self::upgradeStatements( $db ) as $statement )
        {
            if ( $db->query( $statement ) === false )
                $errors[] = $engine . ': ' . substr( $statement, 0, 120 );
            else
                $created[] = 'upgrade: ' . substr( $statement, 0, 120 );
        }
        $missing = self::missingTables( $db );
        if ( !$missing )
            return array( $created, $errors );
        $statements = self::sqlStatements( $engine, $missing );
        if ( !$statements )
            return array( $created, array( "no schema handler for the engine $engine" ) );
        foreach ( $statements as $statement )
        {
            if ( $db->query( $statement ) === false )
                $errors[] = $engine . ': ' . substr( $statement, 0, 120 );
        }
        $remaining = self::missingTables( $db );
        return array( array_merge( $created, array_values( array_diff( $missing, $remaining ) ) ), $errors );
    }

    /**
     * Rewrites share/db_schema.dba and sql/<engine>/schema.sql of the extension in $base from definition().
     *
     * @param string $base the extension directory
     * @return array ( string[] written, string[] errors )
     */
    public static function writeFiles( $base )
    {
        $written = array();
        $errors = array();
        if ( @file_put_contents( "$base/share/db_schema.dba", self::dbaText() ) === false )
            $errors[] = "could not write $base/share/db_schema.dba";
        else
            $written[] = 'share/db_schema.dba';
        foreach ( array( 'mysql', 'postgresql', 'sqlite', 'oracle' ) as $engine )
        {
            $statements = self::sqlStatements( $engine );
            if ( !$statements )
            {
                $errors[] = "no schema handler for $engine";
                continue;
            }
            $text = "-- 7x SQLI Import: the tables " . implode( ', ', self::tables() ) . " ($engine).\n"
                  . "-- Generated from expImportSchema::definition() by ./console ext:sqliimport:install-schema --write-files with the\n"
                  . "-- kernel's schema handler; ./console ext:sqliimport:install-schema creates the same tables in a running installation.\n\n";
            foreach ( $statements as $statement )
                $text .= $statement . ( substr( $statement, -1 ) === ';' ? "\n" : ";\n" ) . ( preg_match( '/^CREATE (TABLE|OR REPLACE TRIGGER)/i', $statement ) ? "\n" : '' );
            if ( $engine === 'oracle' )
                $text = preg_replace( '/^(END;)$/m', "$1\n/", $text );
            if ( !is_dir( "$base/sql/$engine" ) )
                mkdir( "$base/sql/$engine", 0755, true );
            if ( @file_put_contents( "$base/sql/$engine/schema.sql", $text ) === false )
                $errors[] = "could not write sql/$engine/schema.sql";
            else
                $written[] = "sql/$engine/schema.sql (" . count( $statements ) . ' statements)';
        }
        return array( $written, $errors );
    }

    /** @return bool whether every table of the extension exists */
    public static function installed( $db = null )
    {
        return !self::missingTables( $db );
    }
