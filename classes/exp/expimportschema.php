/**
 * The tables of 7x SQLI Import, defined once here in the kernel's generic schema format. share/db_schema.dba and
 * sql/<engine>/schema.sql are generated from it (./console ext:sqliimport:install-schema --write-files), and ensure()
 * creates what is missing in the current database with the kernel's schema handler of that database (MySQL,
 * PostgreSQL, SQLite, Oracle). Every name stays within Oracle's 30 characters, and no new column is a reserved word of
 * any of the engines (hence severity, outcome, row_ref, trigger_kind).
 *
 *   sqliimport_definition     an import: source, processing (mapping or handler), target, behaviour, typed options
 *   sqliimport_mapping        the no-code mapping of an import: target class, match key, language, location rules
 *   sqliimport_mapping_field  one line of a mapping: source path to class attribute, with its transform chain
 *   sqliimport_schedule       when an import runs by itself: once, every N minutes, daily ... or a cron expression
 *   sqliimport_run            one run of an import: trigger, user, status, counters, timings, memory peak
 *   sqliimport_run_row        one record of a run: what was done to which object, version before and after
 *   sqliimport_run_log        the log of a run: severity, record, message, context
 *   sqliimport_notice         a run that ended, for the user who is told about it
 *   sqliimport_trigger        the webhook / API trigger of an import: on or off, run user, data push, signing salt
 *   sqliimport_trigger_key    an API key of a trigger: label, key id, hash (never the key), last use, revoked
 *   sqliimport_trigger_call   the calls of the last minutes: used signatures (replay protection) and the rate limit
 *
 * The tables of 1.x (sqliimport_item, sqliimport_scheduled) stay as they were: 1.x handlers and their history keep
 * working, and ./console ext:sqliimport:migrate-1x reads them.
 *
 * An installation of an earlier state gets the missing columns and indexes from ensure() too (ALTER TABLE ADD,
 * generated by the same handlers), so installing the schema is also the upgrade.
 */
